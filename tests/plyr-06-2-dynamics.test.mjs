import test from 'node:test';
import assert from 'node:assert/strict';
import {makeWorld} from '../src/domain/world.js';
import {enableAdvancedCareer} from '../src/domain/advanced-career.js';
import {enableCareerPersonality,personalityEnabled,validateCareerPersonality,syncCareerPersonality,recordCareerPersonalityEvent,applyCareerMoraleAdjustment,settleCareerPersonalityRound,settleCareerPersonalitySeason,lockerRoomView} from '../src/domain/career-personality.js';
