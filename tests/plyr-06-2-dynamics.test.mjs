const setup=()=>{
 const w=makeWorld(1692,'IT');w.clubId=w.teams[0].id;
 enableAdvancedCareer(w);enableCareerPersonality(w);
 w.lineup=w.players.filter(p=>p.clubId===w.clubId).slice(0,11).map(p=>p.id);
 assert.equal(validateCareerPersonality(w),true);
 return w;
};
test('PLYR-06.2: schema v2 has one authoritative morale and seven trait leadership',()=>{
 const w=setup(),p=w.players.find(p=>p.clubId===w.clubId),st=w.advancedV1.personalityV1.playerStates[String(p.id)];
 assert.equal(st.schemaVersion,2);
 assert.equal(w.advancedV1.personalityV1.schemaVersion,2);
 assert.equal(st.morale,p.morale);
 const profile=generatePersonality({id:p.id,globalId:p.globalId},{seed:w.seed,countryId:w.countryId});
 const other=structuredClone(profile);other.traits.leadership=other.traits.leadership===100?1:100;
 assert.notEqual(playerInfluence(p,profile),playerInfluence(p,other));
 assert.equal(validateDynamics(st),true);
 assert.equal(personalityEnabled(w),true);
});
test('event ledger is bounded, immutable, rejects invalid data and deduplicates IDs beyond history view',()=>{
 const w=setup(),p=w.players.find(p=>p.clubId===w.clubId),profile=p.personalityProfile;
 const first=initialPlayerDynamics(p),clone=structuredClone(first);
 const next=applyPlayerEvent(first,profile,{id:'E1',type:'coach_criticism'});
 assert.deepEqual(first,clone);
 assert.equal(applyPlayerEvent(next,profile,{id:'E1',type:'coach_criticism'}).revision,next.revision);
 assert.equal(next.history.length,1);assert.ok(next.coachRelationship<50);
 assert.throws(()=>applyPlayerEvent(next,profile,{id:'E2',type:'contract_promise',moraleDelta:200}),/DELTA/);
 assert.throws(()=>applyPlayerEvent(next,profile,{id:'E2',type:'played',moraleDelta:1}),/DELTA/);
 assert.throws(()=>applyPlayerEvent(next,profile,{id:'E3',type:'bad'}),/EVENT/);
 let state=next;for(let i=0;i<110;i++)state=applyPlayerEvent(state,profile,{id:'training-'+i,type:'training',importance:0});
 assert.equal(state.history.length,100);
 assert.equal(applyPlayerEvent(state,profile,{id:'E1',type:'played'}).revision,state.revision);
});
test('real match IDs gate round events, draws have exactly one participation event',()=>{
 const w=setup(),s=w.advancedV1.personalityV1,players=w.players.filter(p=>p.clubId===w.clubId);
 const p=players[0],before=s.playerStates[String(p.id)];
 w.round=1;
 const beforeMorale=p.morale;
 assert.equal(settleCareerPersonalityRound(w,{matchId:'match-17',result:'draw',playedIds:[p.id]}),true);
 const after=s.playerStates[String(p.id)];
 assert.equal(after.history.length,1);
 assert.equal(after.history[0].type,'played');
 assert.equal(p.morale,after.morale);
 assert.notEqual(p.morale,beforeMorale);
 const saved=JSON.stringify(w);
 assert.equal(settleCareerPersonalityRound(w,{matchId:'match-17',result:'draw',playedIds:[p.id]}),false);
 assert.equal(JSON.stringify(w),saved);
 assert.equal(s.processedMatches.length,1);
 assert.equal(validateCareerPersonality(w),true);
});
test('win and loss produce bounded outcome plus participation, never double count',()=>{
 const w=setup(),s=w.advancedV1.personalityV1,p=w.players.find(p=>p.clubId===w.clubId);
 w.round=1;
 assert.equal(settleCareerPersonalityRound(w,{matchId:'game-1',result:'win',playedIds:[p.id]}),true);
 const first=s.playerStates[String(p.id)];
 assert.deepEqual(first.history.map(x=>x.type),['win','played']);
 assert.equal(settleCareerPersonalityRound(w,{matchId:'game-1',result:'win',playedIds:[p.id]}),false);
 w.round=2;
 assert.equal(settleCareerPersonalityRound(w,{matchId:'game-2',result:'loss',playedIds:[]}),true);
 const second=s.playerStates[String(p.id)];
 assert.deepEqual(second.history.map(x=>x.type),['win','played','loss','bench']);
 assert.equal(second.morale,p.morale);
 assert.equal(validateCareerPersonality(w),true);
});
